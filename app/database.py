def _backfill_per_cmid_dependencies(connection) -> None:
    """Copy the assistant-wide `cmids_relacionados` to each of its CMID links.

    Only touches assistants whose links have no dependencies yet, so it runs once per assistant:
    after an assistant is saved with per-CMID dependencies, its links are no longer all empty
    (or its assistant-wide list is empty too) and this skips it.
    """
    connection.execute(
        text(
            "UPDATE assistantcmid l SET cmids_relacionados = a.cmids_relacionados "
            "FROM assistantconfig a "
            "WHERE l.assistant_id = a.id "
            "AND a.usa_cmid_relacionado "
            "AND COALESCE(a.cmids_relacionados::text, '[]') <> '[]' "
            "AND NOT EXISTS ("
            "  SELECT 1 FROM assistantcmid o WHERE o.assistant_id = a.id "
            "  AND COALESCE(o.cmids_relacionados::text, '[]') <> '[]'"
            ")"
        )
    )


def _backfill_assistant_cmid_links(connection) -> None:
    """Populate `assistantcmid`/`cmids_relacionados` from the old single-cmid columns.

    Safe to run on every startup: once a row is backfilled it no longer matches the WHERE
    clauses below, so this becomes a no-op. Only touches databases that still have the old
    `cmid`/`cmid_relacionado` columns (pre multi-cmid schema).
    """
    has_old_cmid_column = connection.execute(
        text(
            "SELECT 1 FROM information_schema.columns "
            "WHERE table_name = 'assistantconfig' AND column_name = 'cmid'"
        )
    ).first()
    if not has_old_cmid_column:
        return

    connection.execute(
        text(
            "INSERT INTO assistantcmid (cmid, assistant_id) "
            "SELECT cmid, id FROM assistantconfig "
            "ON CONFLICT (cmid) DO NOTHING"
        )
    )

    has_old_related_column = connection.execute(
        text(
            "SELECT 1 FROM information_schema.columns "
            "WHERE table_name = 'assistantconfig' AND column_name = 'cmid_relacionado'"
        )
    ).first()
    if has_old_related_column:
        connection.execute(
            text(
                "UPDATE assistantconfig SET cmids_relacionados = jsonb_build_array(cmid_relacionado)::json "
                "WHERE cmid_relacionado IS NOT NULL AND (cmids_relacionados IS NULL OR cmids_relacionados::text = '[]')"
            )
        )
