from pathlib import Path

from sqlalchemy import text
from sqlmodel import Session, SQLModel, create_engine

import app.models  # noqa: F401
from app.config import settings


def _ensure_sqlite_parent() -> None:
    if settings.resolved_database_url.startswith("sqlite:///"):
        db_path = settings.resolved_database_url.replace("sqlite:///", "", 1)
        Path(db_path).parent.mkdir(parents=True, exist_ok=True)


_ensure_sqlite_parent()
engine = create_engine(settings.resolved_database_url, echo=False)


def create_db_and_tables() -> None:
    _pre_migrate_assistant_config_pk()
    SQLModel.metadata.create_all(engine)
    _apply_lightweight_migrations()


def get_session():
    with Session(engine) as session:
        yield session


def _pre_migrate_assistant_config_pk() -> None:
    """Give `assistantconfig` an autogenerated `id` primary key before `create_all` runs.

    `assistantcmid` (created by `create_all`) has a foreign key to `assistantconfig.id`, which
    requires that column to already exist and be unique/PK. This only does anything against a
    database created before the multi-cmid change (detected by the missing `id` column); a fresh
    database already gets `id` as the primary key straight from the model. Nothing is dropped here.
    """
    if not settings.resolved_database_url.startswith("postgresql"):
        return

    with engine.begin() as connection:
        table_exists = connection.execute(
            text("SELECT 1 FROM information_schema.tables WHERE table_name = 'assistantconfig'")
        ).first()
        if not table_exists:
            return

        has_id_column = connection.execute(
            text(
                "SELECT 1 FROM information_schema.columns "
                "WHERE table_name = 'assistantconfig' AND column_name = 'id'"
            )
        ).first()
        if has_id_column:
            return

        connection.execute(text("ALTER TABLE assistantconfig ADD COLUMN id SERIAL"))
        pk_constraint = connection.execute(
            text(
                "SELECT tc.constraint_name FROM information_schema.table_constraints tc "
                "WHERE tc.table_name = 'assistantconfig' AND tc.constraint_type = 'PRIMARY KEY'"
            )
        ).first()
        if pk_constraint:
            connection.execute(text(f'ALTER TABLE assistantconfig DROP CONSTRAINT "{pk_constraint[0]}"'))
        connection.execute(text("ALTER TABLE assistantconfig ADD PRIMARY KEY (id)"))


